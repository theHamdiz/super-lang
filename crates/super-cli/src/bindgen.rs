//! `super bindgen` — generate C/C++ headers from exported Super declarations.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use super_core::Interner;
use super_frontend::analyze_project;
use super_frontend::ast::{Item, TypeExpr};
use super_frontend::sema::{TypeKind, TypedModule};

/// Generate a C header (and optional C++ wrappers) for `+` exports in `file`.
pub fn generate(file: &Path, out: &Path) -> Result<(), String> {
    let result = analyze_project(file);
    if result.diagnostics.has_errors() {
        let msg = result
            .diagnostics
            .iter()
            .map(|d| d.to_string())
            .collect::<Vec<_>>()
            .join("; ");
        return Err(msg);
    }
    let stem = file
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("super_module");
    let guard = format!("SUPER_BINDGEN_{}_H", stem.to_uppercase().replace('-', "_"));
    let mut h = String::new();
    writeln!(h, "/* Auto-generated by `super bindgen` — do not edit. */").unwrap();
    writeln!(h, "#ifndef {guard}").unwrap();
    writeln!(h, "#define {guard}").unwrap();
    writeln!(h).unwrap();
    writeln!(h, "#include <stddef.h>").unwrap();
    writeln!(h, "#include <stdint.h>").unwrap();
    writeln!(h, "#include <stdbool.h>").unwrap();
    writeln!(h, "#include \"super.h\"").unwrap();
    writeln!(h).unwrap();
    writeln!(h, "#ifdef __cplusplus").unwrap();
    writeln!(h, "extern \"C\" {{").unwrap();
    writeln!(h, "#endif").unwrap();
    writeln!(h).unwrap();

    // Constants
    for item in &result.module.items {
        if let Item::Binding(b) = item {
            if !b.exported {
                continue;
            }
            let name = result.interner.resolve(b.name);
            if let Some(lit) = const_literal(&b.value, &result.interner) {
                writeln!(h, "#define SUPER_{} {}", name.to_uppercase(), lit).unwrap();
            }
        }
    }
    writeln!(h).unwrap();

    // Structs
    for item in &result.module.items {
        if let Item::Struct(s) = item {
            if !s.exported {
                continue;
            }
            let name = result.interner.resolve(s.name);
            writeln!(h, "typedef struct Super{name} {{").unwrap();
            if let Some(tid) = result.typed.structs.get(&s.name)
                && let TypeKind::Struct { fields, size, .. } = result.typed.types.get_type(*tid)
            {
                for f in fields {
                    if f.private {
                        continue;
                    }
                    let fname = result.interner.resolve(f.name);
                    let cty = c_type_name(&result.typed, &result.interner, f.ty);
                    writeln!(h, "  {cty} {fname};").unwrap();
                }
                writeln!(h, "}} Super{name};").unwrap();
                writeln!(
                    h,
                    "_Static_assert(sizeof(Super{name}) == {size}, \"Super{name} size mismatch\");"
                )
                .unwrap();
                writeln!(h).unwrap();
                continue;
            }
            for f in &s.fields {
                if f.private {
                    continue;
                }
                let fname = result.interner.resolve(f.name);
                let cty = type_expr_c(&f.ty, &result.interner);
                writeln!(h, "  {cty} {fname};").unwrap();
            }
            writeln!(h, "}} Super{name};").unwrap();
            writeln!(h).unwrap();
        }
    }

    // Sum types as tagged unions (C ABI: tag + max payload padding).
    for item in &result.module.items {
        if let Item::Sum(s) = item {
            if !s.exported {
                continue;
            }
            let name = result.interner.resolve(s.name);
            writeln!(h, "typedef struct Super{name} {{").unwrap();
            writeln!(h, "  uint32_t tag;").unwrap();
            writeln!(h, "  union {{").unwrap();
            for (i, v) in s.variants.iter().enumerate() {
                let vname = result.interner.resolve(v.name);
                if v.fields.is_empty() {
                    writeln!(h, "    uint8_t _{vname}_pad;").unwrap();
                } else {
                    writeln!(h, "    struct {{").unwrap();
                    for (fname, fty) in &v.fields {
                        let fnm = result.interner.resolve(*fname);
                        let cty = type_expr_c(fty, &result.interner);
                        writeln!(h, "      {cty} {fnm};").unwrap();
                    }
                    writeln!(h, "    }} {vname};").unwrap();
                }
                let _ = i;
            }
            writeln!(h, "  }} as;").unwrap();
            writeln!(h, "}} Super{name};").unwrap();
            if let Some(tid) = result.typed.sums.get(&s.name)
                && let TypeKind::Sum { size, .. } = result.typed.types.get_type(*tid)
            {
                writeln!(
                    h,
                    "_Static_assert(sizeof(Super{name}) >= {size}, \"Super{name} size\");"
                )
                .unwrap();
            }
            writeln!(h).unwrap();
        }
    }

    // Function wrappers (typed C helpers around super_call_sig).
    for item in &result.module.items {
        if let Item::Function(f) = item {
            if !f.exported {
                continue;
            }
            let name = result.interner.resolve(f.name);
            let ret = f
                .ret
                .as_ref()
                .map(|t| type_expr_c(t, &result.interner))
                .unwrap_or_else(|| "void".to_string());
            let mut params = String::from("SuperEngine *engine");
            let mut sig_args = Vec::new();
            let mut pack_fields = String::new();
            for (i, p) in f.params.iter().enumerate() {
                let pname = result.interner.resolve(p.name);
                let cty = type_expr_c(&p.ty, &result.interner);
                write!(params, ", {cty} {pname}").unwrap();
                sig_args.push(sig_token(&p.ty, &result.interner));
                writeln!(pack_fields, "  args.{pname} = {pname};",).unwrap();
                let _ = i;
            }
            let sig_ret = f
                .ret
                .as_ref()
                .map(|t| sig_token(t, &result.interner))
                .unwrap_or_else(|| "void".to_string());
            let sig = if sig_args.is_empty() {
                format!("->{sig_ret}")
            } else {
                format!("{}->{sig_ret}", sig_args.join(","))
            };

            writeln!(h, "static inline {ret} super_{stem}_{name}({params}) {{").unwrap();
            if f.params.is_empty() {
                if ret == "void" {
                    writeln!(
                        h,
                        "  (void)super_call_sig(engine, \"{stem}\", \"{name}\", NULL, NULL, \"{sig}\");"
                    )
                    .unwrap();
                } else {
                    writeln!(h, "  {ret} __ret;").unwrap();
                    writeln!(
                        h,
                        "  (void)super_call_sig(engine, \"{stem}\", \"{name}\", NULL, &__ret, \"{sig}\");"
                    )
                    .unwrap();
                    writeln!(h, "  return __ret;").unwrap();
                }
            } else {
                writeln!(h, "  struct {{").unwrap();
                for p in &f.params {
                    let pname = result.interner.resolve(p.name);
                    let cty = type_expr_c(&p.ty, &result.interner);
                    writeln!(h, "    {cty} {pname};").unwrap();
                }
                writeln!(h, "  }} args;").unwrap();
                h.push_str(&pack_fields);
                if ret == "void" {
                    writeln!(
                        h,
                        "  (void)super_call_sig(engine, \"{stem}\", \"{name}\", &args, NULL, \"{sig}\");"
                    )
                    .unwrap();
                } else {
                    writeln!(h, "  {ret} __ret;").unwrap();
                    writeln!(
                        h,
                        "  (void)super_call_sig(engine, \"{stem}\", \"{name}\", &args, &__ret, \"{sig}\");"
                    )
                    .unwrap();
                    writeln!(h, "  return __ret;").unwrap();
                }
            }
            writeln!(h, "}}").unwrap();
            writeln!(h).unwrap();
        }
    }

    writeln!(h, "#ifdef __cplusplus").unwrap();
    writeln!(h, "}} /* extern \"C\" */").unwrap();
    writeln!(h).unwrap();
    writeln!(h, "namespace super {{ namespace {stem} {{").unwrap();
    for item in &result.module.items {
        if let Item::Function(f) = item {
            if !f.exported {
                continue;
            }
            let name = result.interner.resolve(f.name);
            let ret = f
                .ret
                .as_ref()
                .map(|t| type_expr_c(t, &result.interner))
                .unwrap_or_else(|| "void".to_string());
            let mut params = String::from("SuperEngine *engine");
            let mut args = String::from("engine");
            for p in &f.params {
                let pname = result.interner.resolve(p.name);
                let cty = type_expr_c(&p.ty, &result.interner);
                write!(params, ", {cty} {pname}").unwrap();
                write!(args, ", {pname}").unwrap();
            }
            writeln!(
                h,
                "inline {ret} {name}({params}) {{ return ::super_{stem}_{name}({args}); }}"
            )
            .unwrap();
        }
    }
    writeln!(h, "}} }} // namespace super::{stem}").unwrap();
    writeln!(h, "#endif").unwrap();
    writeln!(h).unwrap();
    writeln!(h, "#endif /* {guard} */").unwrap();

    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    fs::write(out, h).map_err(|e| e.to_string())?;
    Ok(())
}

fn const_literal(expr: &super_frontend::ast::Expr, interner: &Interner) -> Option<String> {
    use super_frontend::ast::Expr;
    match expr {
        Expr::Int(n, _) => Some(n.to_string()),
        Expr::Float(f, _) => Some(format!("{f}")),
        Expr::Bool(b, _) => Some(if *b { "1" } else { "0" }.into()),
        Expr::String(s, _) => Some(format!("\"{}\"", interner.resolve(*s))),
        _ => None,
    }
}

fn c_type_name(typed: &TypedModule, interner: &Interner, tid: super_core::TypeId) -> String {
    match typed.types.get_type(tid) {
        TypeKind::Void | TypeKind::Never => "void".into(),
        TypeKind::Bool => "bool".into(),
        TypeKind::U8 => "uint8_t".into(),
        TypeKind::I8 => "int8_t".into(),
        TypeKind::U16 => "uint16_t".into(),
        TypeKind::I16 => "int16_t".into(),
        TypeKind::U32 => "uint32_t".into(),
        TypeKind::I32 => "int32_t".into(),
        TypeKind::U64 => "uint64_t".into(),
        TypeKind::I64 => "int64_t".into(),
        TypeKind::I128 => "__int128".into(),
        TypeKind::F32 => "float".into(),
        TypeKind::F64 => "double".into(),
        TypeKind::Str => "const char *".into(),
        TypeKind::Struct { name, .. } => format!("Super{}", interner.resolve(*name)),
        TypeKind::Sum { name, .. } => format!("Super{}", interner.resolve(*name)),
        _ => "int64_t".into(),
    }
}

fn type_expr_c(ty: &TypeExpr, interner: &Interner) -> String {
    match ty {
        TypeExpr::Named(n, _) => match interner.resolve(*n) {
            "bool" => "bool".into(),
            "u8" => "uint8_t".into(),
            "u16" => "uint16_t".into(),
            "u32" => "uint32_t".into(),
            "u64" => "uint64_t".into(),
            "i8" => "int8_t".into(),
            "i16" => "int16_t".into(),
            "i32" => "int32_t".into(),
            "i128" => "__int128".into(),
            "i64" | "int" => "int64_t".into(),
            "f32" => "float".into(),
            "f64" => "double".into(),
            "str" => "const char *".into(),
            other => format!("Super{other}"),
        },
        TypeExpr::Optional(inner, _) | TypeExpr::Error(inner, _) => type_expr_c(inner, interner),
        _ => "int64_t".into(),
    }
}

fn sig_token(ty: &TypeExpr, interner: &Interner) -> String {
    match ty {
        TypeExpr::Named(n, _) => match interner.resolve(*n) {
            "bool" => "bool".into(),
            "u8" | "u16" | "u32" | "i8" | "i16" | "i32" => "i32".into(),
            "u64" | "i128" => "i64".into(),
            "i64" | "int" => "i64".into(),
            "f32" => "f32".into(),
            "f64" => "f64".into(),
            other => format!("{other}:8"),
        },
        _ => "i64".into(),
    }
}
